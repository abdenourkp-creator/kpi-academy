"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync("assets/js/bm001-lab.js", "utf8");
const window = {};
vm.runInNewContext(source, { window });
const lab = window.KPI_BM001_LAB;
assert.ok(lab, "BM-001 lab should register");
assert.equal(lab.taskCount, 5);
assert.equal(lab.evaluate("unit-difference", "0.45").correct, true);
assert.equal(lab.evaluate("unit-difference", "0.45").unit, "MAD");
assert.equal(lab.evaluate("unit-difference", "0.4").correct, false);
assert.equal(lab.evaluate("quantity-impact", "270").correct, true);
assert.equal(lab.evaluate("annual-impact", "14040").correct, true);
assert.equal(lab.evaluate("unit-validation", "b").correct, true);
assert.equal(lab.evaluate("unit-validation", "a").correct, false);
assert.equal(lab.evaluate("source-validation", "c").correct, true);
assert.equal(lab.evaluate("source-validation", "").valid, false);
assert.equal(lab.evaluate("unknown", "1").valid, false);
console.log("BM-001 lab tests passed: five tasks, calculation tolerances, validation and feedback contracts.");
